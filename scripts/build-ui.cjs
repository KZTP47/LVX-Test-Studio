'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const projectRoot = path.resolve(__dirname, '..');
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex');

function validateManifest(manifest, root = projectRoot) {
  if (manifest?.schemaVersion !== 1 || !Array.isArray(manifest.modules) || !manifest.modules.length) throw Error('UI manifest schema is invalid');
  const output = manifest.output || 'assets/app-modules.js';
  if (typeof output !== 'string' || !/^assets\/[a-zA-Z0-9_/-]+\.js$/.test(output) || output.split('/').includes('..')) throw Error('Invalid UI bundle output');
  const modules = new Map(), sources = new Set();
  for (const item of manifest.modules) {
    if (!item || !/^[a-z][a-z0-9-]*$/.test(item.id || '') || modules.has(item.id)) throw Error('Duplicate or invalid UI module id: ' + item?.id);
    if (typeof item.source !== 'string' || !/^[a-zA-Z0-9_./-]+\.js$/.test(item.source) || path.isAbsolute(item.source) || item.source.split('/').includes('..')) throw Error('Invalid UI module source: ' + item.source);
    if (sources.has(item.source.toLowerCase())) throw Error('Duplicate UI module source: ' + item.source);
    const source = path.resolve(root, item.source), relative = path.relative(root, source);
    if (relative.startsWith('..') || !fs.existsSync(source) || !fs.statSync(source).isFile()) throw Error('Missing UI module source: ' + item.source);
    if (path.relative(fs.realpathSync(root), fs.realpathSync(source)).startsWith('..')) throw Error('UI module source escapes project: ' + item.source);
    if (item.source.toLowerCase() === output.toLowerCase()) throw Error('UI bundle output cannot overwrite its source');
    if (!Array.isArray(item.dependsOn) || new Set(item.dependsOn).size !== item.dependsOn.length || item.dependsOn.some(id => typeof id !== 'string')) throw Error('Invalid or duplicate UI dependencies: ' + item.id);
    if (item.external !== undefined && typeof item.external !== 'boolean') throw Error('Invalid external flag: ' + item.id);
    modules.set(item.id, item); sources.add(item.source.toLowerCase());
  }
  for (const item of modules.values()) for (const id of item.dependsOn) {
    if (!modules.has(id)) throw Error('Unknown UI dependency ' + id + ' in ' + item.id);
    if (item.external && !modules.get(id).external) throw Error('External script cannot depend on a bundled script: ' + item.id);
  }
  const ordered = [], pending = new Set(modules.keys());
  while (pending.size) {
    const ready = [...pending].filter(id => modules.get(id).dependsOn.every(dependency => !pending.has(dependency))).sort();
    if (!ready.length) throw Error('UI dependency cycle: ' + [...pending].sort().join(', '));
    for (const id of ready) { ordered.push(modules.get(id)); pending.delete(id); }
  }
  return ordered;
}

function renderBundle(manifest, root = projectRoot) {
  const ordered = validateManifest(manifest, root), bundled = ordered.filter(item => !item.external);
  const parts = ['/* Generated by scripts/build-ui.cjs from ui-modules.json. Do not edit. */'];
  for (const item of bundled) {
    const source = fs.readFileSync(path.join(root, item.source), 'utf8').replace(/\r\n/g, '\n');
    parts.push(`\n;/* module: ${item.id}; source: ${item.source}; sha256: ${sha256(source)} */\n${source}\n;`);
  }
  const content = parts.join('\n') + '\n';
  // A single synchronous classic script retains inline-handler globals and DOMContentLoaded timing.
  new vm.Script(content, { filename: manifest.output || 'assets/app-modules.js' });
  return { content, modules: bundled.map(item => item.id), externals: ordered.filter(item => item.external).map(item => item.source), sha256: sha256(content) };
}

function buildUI({ root = projectRoot, manifest = JSON.parse(fs.readFileSync(path.join(root, 'ui-modules.json'), 'utf8')), check = false } = {}) {
  const result = renderBundle(manifest, root), output = path.resolve(root, manifest.output || 'assets/app-modules.js');
  if (path.relative(root, output).startsWith('..') || path.isAbsolute(path.relative(root, output))) throw Error('Bundle output must stay inside the project');
  if (check) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== result.content) throw Error('UI bundle is stale; run node scripts/build-ui.cjs');
  } else {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    const temp = output + '.' + process.pid + '.tmp';
    try { fs.writeFileSync(temp, result.content); fs.renameSync(temp, output); }
    finally { if (fs.existsSync(temp)) fs.unlinkSync(temp); }
  }
  return result;
}

module.exports = { validateManifest, renderBundle, buildUI };
if (require.main === module) {
  try { const result = buildUI({ check: process.argv.includes('--check') }); console.log('LVX_UI_BUNDLE_VERIFIED ' + result.modules.length + ' modules ' + result.sha256); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
